function walkDir(dir, callback) {
  fs.readdirSync(dir).forEach(f => {
    const dirPath = path.join(dir, f);
    const isDirectory = fs.statSync(dirPath).isDirectory();
    isDirectory ? walkDir(dirPath, callback) : callback(path.join(dir, f));
  });
}

const rootDir = path.resolve(__dirname, '../../');
walkDir(rootDir, filePath => {
  if (filePath.includes('node_modules') || filePath.includes('.git') || filePath.includes('dev-scripts')) return;
  if (!filePath.endsWith('.html')) return;
  
  let content = fs.readFileSync(filePath, 'utf8');
  let changed = false;

  for (const [emoji, svg] of Object.entries(svgMap)) {
    const regex = new RegExp(emoji.replace(/[.*+?^${}()|[\\]\\\\]/g, '\\\\$&'), 'g');
    if (regex.test(content)) {
      content = content.replace(regex, svg);
      changed = true;
    }
  }
  
  if (changed) {
    fs.writeFileSync(filePath, content);
    console.log(`Updated symbols in ${path.relative(rootDir, filePath)}`);
  }
});
